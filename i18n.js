let currentLang = localStorage.getItem('pl_lang') || 'en';

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS['en'][key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-ph'));
  });
  // Update lang toggle button appearance
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.innerHTML = currentLang === 'en'
      ? '<span style="font-weight:800;color:var(--ink);">EN</span> <span style="opacity:0.4;margin:0 3px;">|</span> <span style="opacity:0.5;">TH</span>'
      : '<span style="opacity:0.5;">EN</span> <span style="opacity:0.4;margin:0 3px;">|</span> <span style="font-weight:800;color:var(--ink);">TH</span>';
  }
  // Update html lang attribute
  document.documentElement.lang = currentLang === 'th' ? 'th' : 'en';
}

function toggleLang() {
  currentLang = currentLang === 'en' ? 'th' : 'en';
  localStorage.setItem('pl_lang', currentLang);
  applyTranslations();
}

document.addEventListener('DOMContentLoaded', applyTranslations);
